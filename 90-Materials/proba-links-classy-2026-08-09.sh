#!/usr/bin/env bash
# Проба классов чекера ссылок после трёх правок за ночь.
# Каждый случай — отдельный класс; вместе они проверяют, что ни один не съел соседний.
S="/private/tmp/claude-501/-Users-bubblemac-stack-vault/33ae1170-1bd6-4343-87a7-1618ab75e1c3/scratchpad"
V="$S/lv"; rm -rf "$V"; mkdir -p "$V/00-Board"
w() { printf -- "---\ntitle: %s\n---\n\nтело\n" "$1" > "$V/00-Board/$1.md"; }

w "дело"; w "delo"                       # разные заметки: кириллица и латиница
w "мир";  w "mir"                        # два транслит-кандидата
w "session-state-do-2026-08-06"          # однозначный транслит
w "про- дело"                            # имя после замены «:» на «-»

{ printf -- "---\ntitle: linker\n---\n\n"
  printf -- "регистр: [[Дело]]\n"
  printf -- "двоеточие и регистр: [[ПРО: ДЕЛО]]\n"
  printf -- "спорный транслит: [[миръ]]\n"
  printf -- "однозначный транслит: [[session-state-до-2026-08-06]]\n"
  printf -- "живая ссылка: [[дело]]\n"
} > "$V/00-Board/linker.md"

out="$(bash "$HOME/.claude/hooks/check-links.sh" --vault "$V" 2>&1)"
echo "$out" | grep -E "Итого"
echo "── разбор по классам ──"

has() { printf '%s' "$out" | grep -qF "$1"; }

has "[[Дело]]"     && echo "  ПРОВАЛ  [[Дело]] показана (Obsidian её резолвит, разница только в регистре)" \
                   || echo "  ok      [[Дело]] молчит — кликается"
has "[[ПРО: ДЕЛО]]" && echo "  ok      [[ПРО: ДЕЛО]] замечена — двоеточие Obsidian не простит" \
                    || echo "  ПРОВАЛ  [[ПРО: ДЕЛО]] пропущена: клик создаст заглушку"
has "[[миръ]]"     && echo "  ok      [[миръ]] замечена — два кандидата, цель неизвестна" \
                   || echo "  ПРОВАЛ  спорный транслит пропущен"
has "session-state-do-2026-08-06" && echo "  ok      однозначный транслит определён с целью" \
                                  || echo "  ПРОВАЛ  потеряна починка круга 2"
rm -rf "$V"
