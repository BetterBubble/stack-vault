#!/usr/bin/env bash
# Проба очереди решений: маркер в коде не считается, пустой маркер не считается,
# настоящая развилка попадает целиком (включая двоеточия внутри текста).
S="/private/tmp/claude-501/-Users-bubblemac-stack-vault/33ae1170-1bd6-4343-87a7-1618ab75e1c3/scratchpad"
V="$S/wq"; rm -rf "$V"; mkdir -p "$V/00-Board"

{ printf -- "---\ntitle: карточка\n---\n\n"
  printf -- "@ЖДЁТ: мержить ли ветку QA сейчас · [[карточка]]\n\n"
  printf -- "Как ставить маркер, из инструкции:\n\n"
  printf -- '```\n@ЖДЁТ: одна фраза — что решить · [[карточка]]\n```\n\n'
  printf -- "    @ЖДЁТ: пример с отступом\n\n"
  printf -- "@ЖДЁТ:\n\n"
  printf -- "@ЖДЁТ: развилка с двоеточием: брать вариант А или Б\n"
} > "$V/00-Board/card.md"

bash "$HOME/.claude/hooks/waiting-queue.sh" --vault "$V" >/dev/null 2>&1
# Берём ТОЛЬКО секцию очереди: в шапке готового файла лежит инструкция с примером маркера, и
# первая версия пробы искала по всему файлу — примеры из инструкции засчитывались как пункты
# очереди, а теги шапки («- board», «- queue») как строки списка. Проба врала на исправном коде.
res="$(awk '/^## Ждёт решения/,/^## Похоже/' "$V/00-Board/_zhdet-resheniya.md")"
echo "── собранная очередь ──"
printf '%s\n' "$res" | grep '^- ' | sed 's/^/  /'
echo "── разбор ──"
n="$(printf '%s' "$res" | grep -c '^- ')"

printf '%s' "$res" | grep -q "мержить ли ветку QA" && echo "  ok     настоящая развилка взята" \
                                                   || echo "  ПРОВАЛ развилка потеряна"
printf '%s' "$res" | grep -q "одна фраза — что решить" && echo "  ПРОВАЛ пример из код-блока попал в очередь" \
                                                       || echo "  ok     код-блок не считается"
printf '%s' "$res" | grep -q "пример с отступом" && echo "  ПРОВАЛ код с отступом попал в очередь" \
                                                 || echo "  ok     код с отступом не считается"
printf '%s' "$res" | grep -qE '^- @ЖДЁТ\s*·' && echo "  ПРОВАЛ пустой маркер попал в очередь" \
                                             || echo "  ok     пустой маркер не считается"
printf '%s' "$res" | grep -q "брать вариант А или Б" && echo "  ok     двоеточие внутри текста не обрезало строку" \
                                                     || echo "  ПРОВАЛ текст обрезан по двоеточию"
echo "  всего пунктов: $n (ожидаем 2)"
rm -rf "$V"
